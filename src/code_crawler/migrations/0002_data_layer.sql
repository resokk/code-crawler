-- Слой данных: структура прикладной БД. Живёт отдельно от графа кода
-- и перезаписывается целиком при каждом импорте.
CREATE TABLE data_tables (
    id      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    schema  text NOT NULL,
    name    text NOT NULL,
    kind    text NOT NULL,
    comment text,
    UNIQUE (schema, name)
);

CREATE INDEX data_tables_name_idx ON data_tables (name);

CREATE TABLE data_columns (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    table_id    bigint NOT NULL REFERENCES data_tables ON DELETE CASCADE,
    name        text NOT NULL,
    position    integer NOT NULL,
    data_type   text NOT NULL,
    nullable    boolean NOT NULL,
    primary_key boolean NOT NULL,
    comment     text,
    UNIQUE (table_id, name)
);

CREATE TABLE data_foreign_keys (
    name          text NOT NULL,
    column_id     bigint NOT NULL REFERENCES data_columns ON DELETE CASCADE,
    ref_column_id bigint NOT NULL REFERENCES data_columns ON DELETE CASCADE
);

CREATE INDEX data_foreign_keys_column_idx ON data_foreign_keys (column_id);
CREATE INDEX data_foreign_keys_ref_column_idx ON data_foreign_keys (ref_column_id);

-- Ссылки из кода на слой данных. Хранятся по имени, а не по id:
-- индексы репозиториев и слой данных обновляются независимо друг от друга.
CREATE TABLE data_refs (
    node_id     bigint NOT NULL REFERENCES nodes ON DELETE CASCADE,
    kind        text NOT NULL,
    table_name  text NOT NULL,
    column_name text,
    attrs       jsonb NOT NULL DEFAULT '{}'
);

CREATE INDEX data_refs_node_idx ON data_refs (node_id);
CREATE INDEX data_refs_target_idx ON data_refs (table_name, column_name);
