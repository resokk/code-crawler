CREATE TABLE repos (
    id          bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    name        text NOT NULL UNIQUE,
    source      text NOT NULL,
    path        text NOT NULL,
    branch      text,
    commit_hash text,
    indexed_at  timestamptz
);

-- id узлов выдаёт индексатор из последовательности, чтобы грузить узлы и рёбра через COPY.
CREATE TABLE nodes (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repo_id        bigint NOT NULL REFERENCES repos ON DELETE CASCADE,
    kind           text NOT NULL,
    name           text NOT NULL,
    qualified_name text NOT NULL,
    file_path      text,
    start_line     integer,
    end_line       integer,
    attrs          jsonb NOT NULL DEFAULT '{}'
);

CREATE INDEX nodes_repo_kind_idx ON nodes (repo_id, kind);

CREATE TABLE edges (
    src_id bigint NOT NULL REFERENCES nodes ON DELETE CASCADE,
    dst_id bigint NOT NULL REFERENCES nodes ON DELETE CASCADE,
    kind   text NOT NULL,
    attrs  jsonb NOT NULL DEFAULT '{}'
);

CREATE INDEX edges_src_idx ON edges (src_id, kind);
CREATE INDEX edges_dst_idx ON edges (dst_id, kind);
